//! Vulkan vertex attribute format mapping.
use ash::vk;
use fluxel_rhi_core::api;

pub(crate) fn vformat(v: api::VertexFormat) -> Option<vk::Format> {
    match v {
        api::VertexFormat::Float32(1) => Some(vk::Format::R32_SFLOAT),
        api::VertexFormat::Float32(2) => Some(vk::Format::R32G32_SFLOAT),
        api::VertexFormat::Float32(3) => Some(vk::Format::R32G32B32_SFLOAT),
        api::VertexFormat::Float32(4) => Some(vk::Format::R32G32B32A32_SFLOAT),
        api::VertexFormat::Float16(1) => Some(vk::Format::R16_SFLOAT),
        api::VertexFormat::Float16(2) => Some(vk::Format::R16G16_SFLOAT),
        api::VertexFormat::Float16(3) => Some(vk::Format::R16G16B16_SFLOAT),
        api::VertexFormat::Float16(4) => Some(vk::Format::R16G16B16A16_SFLOAT),
        api::VertexFormat::Uint32(1) => Some(vk::Format::R32_UINT),
        api::VertexFormat::Uint32(2) => Some(vk::Format::R32G32_UINT),
        api::VertexFormat::Uint32(3) => Some(vk::Format::R32G32B32_UINT),
        api::VertexFormat::Uint32(4) => Some(vk::Format::R32G32B32A32_UINT),
        api::VertexFormat::Sint32(1) => Some(vk::Format::R32_SINT),
        api::VertexFormat::Sint32(2) => Some(vk::Format::R32G32_SINT),
        api::VertexFormat::Sint32(3) => Some(vk::Format::R32G32B32_SINT),
        api::VertexFormat::Sint32(4) => Some(vk::Format::R32G32B32A32_SINT),
        api::VertexFormat::Uint16(1) => Some(vk::Format::R16_UINT),
        api::VertexFormat::Uint16(2) => Some(vk::Format::R16G16_UINT),
        api::VertexFormat::Uint16(3) => Some(vk::Format::R16G16B16_UINT),
        api::VertexFormat::Uint16(4) => Some(vk::Format::R16G16B16A16_UINT),
        api::VertexFormat::Sint16(1) => Some(vk::Format::R16_SINT),
        api::VertexFormat::Sint16(2) => Some(vk::Format::R16G16_SINT),
        api::VertexFormat::Sint16(3) => Some(vk::Format::R16G16B16_SINT),
        api::VertexFormat::Sint16(4) => Some(vk::Format::R16G16B16A16_SINT),
        api::VertexFormat::Uint8(1) => Some(vk::Format::R8_UINT),
        api::VertexFormat::Uint8(2) => Some(vk::Format::R8G8_UINT),
        api::VertexFormat::Uint8(3) => Some(vk::Format::R8G8B8_UINT),
        api::VertexFormat::Uint8(4) => Some(vk::Format::R8G8B8A8_UINT),
        api::VertexFormat::Sint8(1) => Some(vk::Format::R8_SINT),
        api::VertexFormat::Sint8(2) => Some(vk::Format::R8G8_SINT),
        api::VertexFormat::Sint8(3) => Some(vk::Format::R8G8B8_SINT),
        api::VertexFormat::Sint8(4) => Some(vk::Format::R8G8B8A8_SINT),
        api::VertexFormat::Unorm8(1) => Some(vk::Format::R8_UNORM),
        api::VertexFormat::Unorm8(2) => Some(vk::Format::R8G8_UNORM),
        api::VertexFormat::Unorm8(3) => Some(vk::Format::R8G8B8_UNORM),
        api::VertexFormat::Unorm8(4) => Some(vk::Format::R8G8B8A8_UNORM),
        api::VertexFormat::Snorm8(1) => Some(vk::Format::R8_SNORM),
        api::VertexFormat::Snorm8(2) => Some(vk::Format::R8G8_SNORM),
        api::VertexFormat::Snorm8(3) => Some(vk::Format::R8G8B8_SNORM),
        api::VertexFormat::Snorm8(4) => Some(vk::Format::R8G8B8A8_SNORM),
        api::VertexFormat::Unorm16(1) => Some(vk::Format::R16_UNORM),
        api::VertexFormat::Unorm16(2) => Some(vk::Format::R16G16_UNORM),
        api::VertexFormat::Unorm16(3) => Some(vk::Format::R16G16B16_UNORM),
        api::VertexFormat::Unorm16(4) => Some(vk::Format::R16G16B16A16_UNORM),
        api::VertexFormat::Snorm16(1) => Some(vk::Format::R16_SNORM),
        api::VertexFormat::Snorm16(2) => Some(vk::Format::R16G16_SNORM),
        api::VertexFormat::Snorm16(3) => Some(vk::Format::R16G16B16_SNORM),
        api::VertexFormat::Snorm16(4) => Some(vk::Format::R16G16B16A16_SNORM),
        api::VertexFormat::Float64(1) => Some(vk::Format::R64_SFLOAT),
        api::VertexFormat::Float64(2) => Some(vk::Format::R64G64_SFLOAT),
        api::VertexFormat::Float64(3) => Some(vk::Format::R64G64B64_SFLOAT),
        api::VertexFormat::Float64(4) => Some(vk::Format::R64G64B64A64_SFLOAT),
        api::VertexFormat::Uint64(1) => Some(vk::Format::R64_UINT),
        api::VertexFormat::Uint64(2) => Some(vk::Format::R64G64_UINT),
        api::VertexFormat::Uint64(3) => Some(vk::Format::R64G64B64_UINT),
        api::VertexFormat::Uint64(4) => Some(vk::Format::R64G64B64A64_UINT),
        _ => None,
    }
}
